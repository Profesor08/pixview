    // UI text in 13 languages. The language follows the Windows display language unless one is chosen
    // in Settings; --lang=xx or the PIXVIEW_LANG variable override both. A key missing in a language falls back to English.
    // In the tables "\n" stands for a line break; {0}, {1} are placeholders.
    static class L
    {
        public static readonly string[] Codes = { "en", "ru", "uk", "de", "fr", "es", "it", "pt", "pl", "tr", "zh", "ja", "ko" };

        static Dictionary<string, string> current, english;

        public static string Code { get; private set; }

        public static void Init(string forced)
        {
            string saved = AppSettings.Language;
            string code = (forced ?? Environment.GetEnvironmentVariable("PIXVIEW_LANG") ?? (string.IsNullOrEmpty(saved) ? null : saved) ?? CultureInfo.CurrentUICulture.Name).ToLowerInvariant();
            if (code.Length > 2) code = code.Substring(0, 2);
            if (Array.IndexOf(Codes, code) < 0) code = "en";
            Code = code;
            english = Parse(Table("en"));
            current = code == "en" ? english : Parse(Table(code));
        }

        public static string T(string key)
        {
            if (current == null) Init(null);
            string s;
            if (current.TryGetValue(key, out s) || english.TryGetValue(key, out s)) return s;
            return key;
        }

        public static string F(string key, params object[] args)
        {
            return string.Format(T(key), args);
        }

        // keys of a language table (used by the consistency check in the tests)
        public static ICollection<string> Keys(string code)
        {
            return Parse(Table(code)).Keys;
        }

        static Dictionary<string, string> Parse(string table)
        {
            var d = new Dictionary<string, string>();
            foreach (var raw in table.Split('\n'))
            {
                string line = raw.TrimEnd('\r');
                int eq = line.IndexOf('=');
                if (eq <= 0) continue;
                d[line.Substring(0, eq).Trim()] = line.Substring(eq + 1).Replace("\\n", "\n");
            }
            return d;
        }

        static string Table(string code)
        {
            switch (code)
            {
                case "ru": return Ru;
                case "uk": return Uk;
                case "de": return De;
                case "fr": return Fr;
                case "es": return Es;
                case "it": return It;
                case "pt": return Pt;
                case "pl": return Pl;
                case "tr": return Tr;
                case "zh": return Zh;
                case "ja": return Ja;
                case "ko": return Ko;
                default: return En;
            }
        }

